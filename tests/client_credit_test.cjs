const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const ts=require('../mobile/node_modules/typescript');
const src=fs.readFileSync(path.join(__dirname,'../mobile/src/lib/clientCredit.ts'),'utf8');
const js=ts.transpileModule(src,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const calls=[];
let client={id:92,status:'Active',credit:'125.50',currency_code:'USD'};
let mutation={ok:true,data:{result:'success',newbalance:'135.50'}};
const context={exports:{},require(name){
 if(name==='./api')return {callApi:async(_s,action,params)=>{
  calls.push({action,params});
  if(action==='GetClientsDetails')return {ok:true,data:{client}};
  if(action==='AddCredit')return mutation;
  throw Error('unexpected action '+action);
 }};
 throw Error('unexpected import '+name);
}};
vm.runInNewContext(js,context);
const c=context.exports;
const initial=c.readClientCredit({client},92);
assert.equal(initial.amount,125.50);
assert.equal(initial.currency,'USD');
assert.equal(c.formatClientBalance(initial),'125.50 USD');
assert.throws(()=>c.readClientCredit({client:{...client,id:93}},92),/عميل مختلف/);
assert.throws(()=>c.readClientCredit({client:{...client,credit:undefined}},92),/غير متاح/);
assert.throws(()=>c.readClientCredit({client:{...client,currency_code:undefined}},92),/عملة/);
assert.equal(c.parseCreditAmount('10.25'),10.25);
assert.equal(c.parseCreditAmount('1'),1);
for(const raw of ['0','0.00','-1','abc','1.999','1000001','1e2','10,000','']){
 assert.throws(()=>c.parseCreditAmount(raw),undefined,'Rejected: '+raw);
}
for(const raw of ['','a','  ','x'.repeat(241)])assert.throws(()=>c.validateCreditDescription(raw));
assert.equal(c.validateCreditDescription('  تحويل   بنكي   '),'تحويل بنكي');
(async()=>{
 const session={baseUrl:'https://whmcs.example'};
 let res=await c.addClientCredit(session,92,'10.00','استلام تحويل بنكي','USD');
 assert.equal(res.ok,true);assert.equal(res.data.newBalance,135.50);
 assert.equal(calls.length,2);
 assert.equal(calls[0].action,'GetClientsDetails');
 assert.equal(calls[0].params.clientid,92);
 assert.equal(calls[1].action,'AddCredit');
 assert.equal(calls[1].params.clientid,92);
 assert.equal(calls[1].params.type,'add');
 assert.equal(calls[1].params.amount,'10.00');
 assert.equal(calls[1].params.description,'استلام تحويل بنكي');
 assert.ok(!('invoiceid' in calls[1].params),'Credit must not be applied to an invoice');
 assert.ok(!('date' in calls[1].params),'Let WHMCS record authoritative credit date');
 calls.length=0;
 res=await c.addClientCredit(session,92,'0','test case','USD');
 assert.equal(res.ok,false);assert.equal(calls.length,0,'Invalid amount cannot hit API');
 client={...client,id:93};
 res=await c.addClientCredit(session,92,'10','استلام دفعة','USD');
 assert.equal(res.ok,false);assert.equal(calls.length,1,'Other client is never credited');
 client={...client,id:92};
 calls.length=0;
 res=await c.addClientCredit(session,92,'10','رصيد تجريبي','EUR');
 assert.equal(res.ok,false);assert.equal(calls.length,1,'Currency mismatch never credits');
 calls.length=0;
 mutation={ok:false,code:'NETWORK_ERROR',error:'Connection dropped after POST'};
 res=await c.addClientCredit(session,92,'10','إيداع مؤكد','USD');
 assert.equal(res.ok,false);
 assert.match(res.error,/لا تضغط إضافة مرة ثانية تلقائيًا/);
 assert.equal(calls.filter(x=>x.action==='AddCredit').length,1,'No repeat on ambiguous result');
 calls.length=0;
 mutation={ok:true,data:{result:'success'}};
 res=await c.addClientCredit(session,92,'10','دفعة مستلمة','USD');
 assert.equal(res.ok,false);
 assert.match(res.error,/لا تعِد الإضافة/);
 assert.equal(calls.filter(x=>x.action==='AddCredit').length,1);
 console.log('PASS: official AddCredit, owner/currency/balance checks, required reason, no accidental invoice payments, no unsafe retry');
})().catch(e=>{console.error(e);process.exit(1)});
