const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const ts=require('../mobile/node_modules/typescript');
const file=fs.readFileSync(path.join(__dirname,'../mobile/src/lib/invoicePresentation.ts'),'utf8');
const compiled=ts.transpileModule(file,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const module={exports:{}};
vm.runInNewContext(compiled,{module,exports:module.exports,require() {throw Error('unexpected runtime import')}});
const {invoiceDayIndex,invoiceDue,invoiceSort}=module.exports;
const today=new Date('2026-10-14T12:00:00');
const inv=(id,status,due)=>({id,status,due,customer:'Test Customer',amount:100,currency:'EGP'});
assert.equal(invoiceDayIndex('2026-10-14'),invoiceDayIndex('2026/10/14'));
assert.equal(invoiceDayIndex('31/10/2026'),invoiceDayIndex('2026-10-31'));
assert.equal(invoiceDayIndex('12/10/2026'),null,'ambiguous dates must not be misclassified');
assert.equal(invoiceDayIndex('2026-02-30'),null);
assert.equal(invoiceDayIndex('2026-13-14'),null);
assert.equal(invoiceDue(inv(1,'Unpaid','2026-10-07'),today).label,'متأخرة 7 يوم');
assert.equal(invoiceDue(inv(2,'Unpaid','2026-10-20'),today).label,'متبقي 6 يوم');
assert.equal(invoiceDue(inv(3,'Unpaid','2026-10-14'),today).label,'مستحقة اليوم');
assert.equal(invoiceDue(inv(4,'Paid','2026-10-01'),today).kind,'paid');
assert.equal(invoiceDue(inv(5,'Cancelled','2026-10-01'),today).kind,'neutral');
assert.equal(invoiceDue(inv(6,'Overdue','invalid'),today).kind,'overdue');
const ordered=[inv(2,'Unpaid','2026-10-20'),inv(3,'Paid','2026-10-01'),inv(1,'Unpaid','2026-10-07'),inv(4,'Unpaid','2026-10-14')]
 .sort((a,b)=>invoiceSort(a,b,today));
assert.deepEqual(Array.from(ordered,x=>x.id),[1,4,2,3]);
const app=fs.readFileSync(path.join(__dirname,'../mobile/App.tsx'),'utf8');
assert.match(app,/page:'invoices',label:'الفواتير',icon:'receipt-text-outline'/);
assert.match(app,/page:'ai',label:'الذكاء الاصطناعي'/);
const home=fs.readFileSync(path.join(__dirname,'../mobile/src/screens/Home.tsx'),'utf8');
assert.match(home,/totals\.invoices/);
assert.match(home,/إجمالي عدد الفواتير/);
const dir=fs.readFileSync(path.join(__dirname,'../mobile/src/screens/Directory.tsx'),'utf8');
assert.match(dir,/inv\.customer/);
assert.match(dir,/invoiceDue\(inv\)/);
assert.ok(!dir.includes("page==='invoices'?'عرض الملف':'التفاصيل'"));
console.log('PASS: WHMCS invoice count, payment-aware red/green due labels, date edge cases, invoice cards and navigation');
